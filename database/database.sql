-- =====================================================================
-- 1. TABEL PELANGGAN
--    Data orang atau instansi yang memesan katering beserta alamat
--    pengirimannya.
-- =====================================================================

CREATE TABLE public.pelanggan (
    id_pelanggan     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pelanggan   VARCHAR(100) NOT NULL,
    no_hp            VARCHAR(20)  NOT NULL,
    alamat           TEXT         NOT NULL,
    patokan_alamat   TEXT,
    jenis_pelanggan  VARCHAR(20)  NOT NULL DEFAULT 'Perorangan'
                     CHECK (jenis_pelanggan IN ('Perorangan', 'Instansi')),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- =====================================================================
-- 2. TABEL PAKET KATERING
--    Daftar paket yang dijual beserta harga per porsi.
-- =====================================================================

CREATE TABLE public.paket_katering (
    id_paket         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_paket       VARCHAR(100)  NOT NULL,
    kategori         VARCHAR(30)   NOT NULL
                     CHECK (kategori IN ('Nasi Kotak', 'Prasmanan', 'Tumpeng',
                                         'Katering Harian', 'Snack Box')),
    harga_per_porsi  NUMERIC(12,2) NOT NULL CHECK (harga_per_porsi > 0),
    minimal_porsi    INTEGER       NOT NULL DEFAULT 1 CHECK (minimal_porsi >= 1),
    deskripsi        TEXT,
    aktif            BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);


-- =====================================================================
-- 3. TABEL PESANAN
--    Mencatat setiap pesanan yang masuk. Harga per porsi disalin dari
--    paket pada saat pesanan dibuat (snapshot), sehingga perubahan harga
--    paket di kemudian hari tidak mengubah nilai pesanan lama.
--    total_tagihan dan status_pembayaran dihitung otomatis oleh database.
-- =====================================================================

CREATE TABLE public.pesanan (
    id_pesanan         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_pesanan       VARCHAR(20)   UNIQUE,
    id_pelanggan       BIGINT        NOT NULL
                       REFERENCES public.pelanggan (id_pelanggan),
    id_paket           BIGINT        NOT NULL
                       REFERENCES public.paket_katering (id_paket),
    tanggal_pesan      DATE          NOT NULL DEFAULT CURRENT_DATE,
    tanggal_kirim      DATE          NOT NULL,
    jam_kirim          TIME          NOT NULL,
    jumlah_porsi       INTEGER       NOT NULL CHECK (jumlah_porsi > 0),
    harga_per_porsi    NUMERIC(12,2) NOT NULL CHECK (harga_per_porsi >= 0),
    ongkos_kirim       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (ongkos_kirim >= 0),
    diskon             NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (diskon >= 0),

    total_tagihan      NUMERIC(14,2) GENERATED ALWAYS AS
                       (jumlah_porsi * harga_per_porsi + ongkos_kirim - diskon) STORED,

    jumlah_dibayar     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (jumlah_dibayar >= 0),
    metode_pembayaran  VARCHAR(20)
                       CHECK (metode_pembayaran IN ('Tunai', 'Transfer', 'QRIS')),

    status_pembayaran  VARCHAR(20) GENERATED ALWAYS AS (
                         CASE
                           WHEN jumlah_dibayar <= 0 THEN 'Belum Bayar'
                           WHEN jumlah_dibayar >= jumlah_porsi * harga_per_porsi
                                                 + ongkos_kirim - diskon THEN 'Lunas'
                           ELSE 'DP'
                         END) STORED,

    status_pesanan     VARCHAR(20)   NOT NULL DEFAULT 'Baru'
                       CHECK (status_pesanan IN ('Baru', 'Diproses', 'Selesai', 'Dibatalkan')),
    catatan            TEXT,
    dicatat_oleh       VARCHAR(150),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT cek_diskon_wajar
        CHECK (diskon <= jumlah_porsi * harga_per_porsi + ongkos_kirim),
    CONSTRAINT cek_tidak_lebih_bayar
        CHECK (jumlah_dibayar <= jumlah_porsi * harga_per_porsi + ongkos_kirim - diskon),
    CONSTRAINT cek_tanggal_kirim
        CHECK (tanggal_kirim >= tanggal_pesan)
);


-- =====================================================================
-- 4. TABEL PENGIRIMAN
--    Setiap pesanan memiliki satu data pengiriman (relasi 1 : 1) yang
--    dibuat otomatis oleh trigger saat pesanan disimpan.
-- =====================================================================

CREATE TABLE public.pengiriman (
    id_pengiriman       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pesanan          BIGINT       NOT NULL UNIQUE
                        REFERENCES public.pesanan (id_pesanan) ON DELETE CASCADE,
    alamat_tujuan       TEXT         NOT NULL,
    nama_penerima       VARCHAR(100),
    no_hp_penerima      VARCHAR(20),
    nama_kurir          VARCHAR(100),
    status_pengiriman   VARCHAR(20)  NOT NULL DEFAULT 'Dijadwalkan'
                        CHECK (status_pengiriman IN ('Dijadwalkan', 'Disiapkan',
                               'Dalam Perjalanan', 'Terkirim', 'Gagal')),
    waktu_berangkat     TIMESTAMPTZ,
    waktu_tiba          TIMESTAMPTZ,
    catatan_pengiriman  TEXT,
    diperbarui_oleh     VARCHAR(150),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


CREATE INDEX idx_pesanan_tanggal_kirim ON public.pesanan (tanggal_kirim);
CREATE INDEX idx_pesanan_pelanggan     ON public.pesanan (id_pelanggan);
CREATE INDEX idx_pesanan_paket         ON public.pesanan (id_paket);
CREATE INDEX idx_pengiriman_status     ON public.pengiriman (status_pengiriman);


-- =====================================================================
-- 5. FUNGSI PERAN PENGGUNA
--    Peran dibaca dari auth.users.raw_app_meta_data (app_metadata), yang
--    tidak dapat diubah sendiri oleh pengguna dari aplikasi. Fungsi
--    SECURITY DEFINER membaca peran langsung dari database, sehingga
--    perubahan peran oleh pemilik langsung berlaku.
-- =====================================================================

-- Peran pengguna yang sedang login: 'pemilik', 'admin', 'kurir',
-- 'nonaktif', atau NULL (belum disetujui).
CREATE OR REPLACE FUNCTION public.peran_saya()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT u.raw_app_meta_data ->> 'peran'
    FROM auth.users u
    WHERE u.id = auth.uid();
$$;

-- TRUE jika peran pengguna termasuk salah satu peran yang disebutkan.
CREATE OR REPLACE FUNCTION public.punya_peran(VARIADIC daftar_peran TEXT[])
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT COALESCE(public.peran_saya() = ANY (daftar_peran), FALSE);
$$;

-- Nama (atau email) pengguna yang sedang login, untuk jejak audit.
CREATE OR REPLACE FUNCTION public.nama_pengguna_saat_ini()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT COALESCE(NULLIF(u.raw_user_meta_data ->> 'nama_lengkap', ''), u.email)
    FROM auth.users u
    WHERE u.id = auth.uid();
$$;


