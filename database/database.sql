-- 6a. Sebelum pesanan disimpan: isi harga dari paket bila kosong,
--     tolak paket nonaktif dan porsi di bawah minimal (khusus pesanan
--     baru), lalu buat kode pesanan otomatis (PSN-0001, PSN-0002, ...).
CREATE OR REPLACE FUNCTION public.fn_pesanan_sebelum_simpan()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_paket public.paket_katering%ROWTYPE;
BEGIN
    SELECT * INTO v_paket
    FROM public.paket_katering
    WHERE id_paket = NEW.id_paket;

    IF NEW.harga_per_porsi IS NULL THEN
        NEW.harga_per_porsi := v_paket.harga_per_porsi;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NOT v_paket.aktif THEN
            RAISE EXCEPTION 'Paket "%" sedang tidak aktif dan tidak dapat dipesan.',
                v_paket.nama_paket;
        END IF;

        IF NEW.jumlah_porsi < v_paket.minimal_porsi THEN
            RAISE EXCEPTION 'Paket "%" minimal % porsi.',
                v_paket.nama_paket, v_paket.minimal_porsi;
        END IF;

        IF NEW.kode_pesanan IS NULL THEN
            NEW.kode_pesanan := 'PSN-' || LPAD(NEW.id_pesanan::TEXT, 4, '0');
        END IF;

        NEW.dicatat_oleh := COALESCE(public.nama_pengguna_saat_ini(), 'Sistem (data contoh)');
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_pesanan_sebelum_simpan
BEFORE INSERT OR UPDATE OF id_paket, jumlah_porsi ON public.pesanan
FOR EACH ROW EXECUTE FUNCTION public.fn_pesanan_sebelum_simpan();


-- 6b. Setelah pesanan dibuat: buat data pengiriman otomatis dengan
--     alamat, nama, dan nomor HP pelanggan.
CREATE OR REPLACE FUNCTION public.fn_buat_pengiriman()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.pengiriman
        (id_pesanan, alamat_tujuan, nama_penerima, no_hp_penerima)
    SELECT
        NEW.id_pesanan,
        p.alamat || COALESCE(' (Patokan: ' || p.patokan_alamat || ')', ''),
        p.nama_pelanggan,
        p.no_hp
    FROM public.pelanggan p
    WHERE p.id_pelanggan = NEW.id_pelanggan;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_buat_pengiriman
AFTER INSERT ON public.pesanan
FOR EACH ROW EXECUTE FUNCTION public.fn_buat_pengiriman();


-- 6c. Sebelum data pengiriman diubah: batasi kolom yang boleh diubah
--     kurir, catat waktu berangkat dan waktu tiba, serta pengubah data.
CREATE OR REPLACE FUNCTION public.fn_waktu_pengiriman()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF public.peran_saya() = 'kurir' AND (
           NEW.alamat_tujuan  IS DISTINCT FROM OLD.alamat_tujuan
        OR NEW.nama_penerima  IS DISTINCT FROM OLD.nama_penerima
        OR NEW.no_hp_penerima IS DISTINCT FROM OLD.no_hp_penerima
        OR NEW.id_pesanan     IS DISTINCT FROM OLD.id_pesanan) THEN
        RAISE EXCEPTION 'Kurir hanya dapat mengubah status, nama kurir, dan catatan pengiriman.';
    END IF;

    IF NEW.status_pengiriman = 'Dalam Perjalanan' AND NEW.waktu_berangkat IS NULL THEN
        NEW.waktu_berangkat := NOW();
    END IF;

    IF NEW.status_pengiriman = 'Terkirim' THEN
        IF NEW.waktu_berangkat IS NULL THEN
            NEW.waktu_berangkat := NOW();
        END IF;
        IF NEW.waktu_tiba IS NULL THEN
            NEW.waktu_tiba := NOW();
        END IF;
    END IF;

    NEW.updated_at := NOW();
    NEW.diperbarui_oleh := COALESCE(public.nama_pengguna_saat_ini(), 'Sistem (data contoh)');
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_waktu_pengiriman
BEFORE UPDATE ON public.pengiriman
FOR EACH ROW EXECUTE FUNCTION public.fn_waktu_pengiriman();


-- 6d. Setelah status pengiriman diubah: sesuaikan status pesanan.
--     Terkirim -> pesanan Selesai (pendapatan diakui).
--     Disiapkan / Dalam Perjalanan / Gagal -> pesanan Diproses.
CREATE OR REPLACE FUNCTION public.fn_sinkron_status_pesanan()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    UPDATE public.pesanan
    SET status_pesanan = CASE
            WHEN NEW.status_pengiriman = 'Terkirim'    THEN 'Selesai'
            WHEN NEW.status_pengiriman = 'Dijadwalkan' THEN 'Baru'
            ELSE 'Diproses'
        END
    WHERE id_pesanan = NEW.id_pesanan
      AND status_pesanan <> 'Dibatalkan';

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sinkron_status_pesanan
AFTER UPDATE OF status_pengiriman ON public.pengiriman
FOR EACH ROW EXECUTE FUNCTION public.fn_sinkron_status_pesanan();


-- =====================================================================
-- 7. VIEW GABUNGAN (dipakai halaman monitoring dan laporan)
--    Menggabungkan keempat tabel dalam satu baris per pesanan.
-- =====================================================================

CREATE VIEW public.v_pesanan_lengkap
WITH (security_invoker = true) AS
SELECT
    ps.id_pesanan,
    ps.kode_pesanan,
    ps.tanggal_pesan,
    ps.tanggal_kirim,
    ps.jam_kirim,
    ps.jumlah_porsi,
    ps.harga_per_porsi,
    ps.ongkos_kirim,
    ps.diskon,
    ps.total_tagihan,
    ps.jumlah_dibayar,
    ps.total_tagihan - ps.jumlah_dibayar AS sisa_tagihan,
    ps.metode_pembayaran,
    ps.status_pembayaran,
    ps.status_pesanan,
    ps.catatan,
    ps.dicatat_oleh,
    ps.created_at AS waktu_dicatat,
    pl.id_pelanggan,
    pl.nama_pelanggan,
    pl.no_hp,
    pl.jenis_pelanggan,
    pk.id_paket,
    pk.nama_paket,
    pk.kategori,
    pg.id_pengiriman,
    pg.alamat_tujuan,
    pg.nama_penerima,
    pg.no_hp_penerima,
    pg.nama_kurir,
    pg.status_pengiriman,
    pg.waktu_berangkat,
    pg.waktu_tiba,
    pg.catatan_pengiriman,
    pg.diperbarui_oleh,
    pg.updated_at AS waktu_diperbarui
FROM public.pesanan ps
JOIN public.pelanggan      pl ON pl.id_pelanggan = ps.id_pelanggan
JOIN public.paket_katering pk ON pk.id_paket     = ps.id_paket
LEFT JOIN public.pengiriman pg ON pg.id_pesanan  = ps.id_pesanan;


