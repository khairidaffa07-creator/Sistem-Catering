-- 9a. Pengguna pertama yang mendaftar otomatis menjadi pemilik.
--     Pengguna berikutnya berstatus "menunggu persetujuan" sampai
--     pemilik memberikan peran dari menu Pengguna.
CREATE OR REPLACE FUNCTION public.fn_pengguna_baru()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM auth.users WHERE raw_app_meta_data ->> 'peran' = 'pemilik'
    ) THEN
        NEW.raw_app_meta_data :=
            COALESCE(NEW.raw_app_meta_data, '{}'::JSONB) || '{"peran": "pemilik"}'::JSONB;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pengguna_baru ON auth.users;
CREATE TRIGGER trg_pengguna_baru
BEFORE INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.fn_pengguna_baru();


-- 9b. Daftar seluruh pengguna (khusus pemilik).
DROP FUNCTION IF EXISTS public.daftar_pengguna();
CREATE FUNCTION public.daftar_pengguna()
RETURNS TABLE (
    id                  UUID,
    email               TEXT,
    nama_lengkap        TEXT,
    peran               TEXT,
    email_terkonfirmasi BOOLEAN,
    login_terakhir      TIMESTAMPTZ,
    dibuat              TIMESTAMPTZ
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT public.punya_peran('pemilik') THEN
        RAISE EXCEPTION 'Hanya pemilik yang dapat melihat daftar pengguna.';
    END IF;

    RETURN QUERY
    SELECT u.id,
           u.email::TEXT,
           (u.raw_user_meta_data ->> 'nama_lengkap')::TEXT,
           (u.raw_app_meta_data  ->> 'peran')::TEXT,
           (u.email_confirmed_at IS NOT NULL),
           u.last_sign_in_at,
           u.created_at
    FROM auth.users u
    ORDER BY u.created_at;
END;
$$;


-- 9c. Mengatur peran pengguna (khusus pemilik). Akun yang diberi peran
--     sekaligus dikonfirmasi emailnya agar dapat langsung login.
CREATE OR REPLACE FUNCTION public.atur_peran_pengguna(p_user_id UUID, p_peran TEXT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT public.punya_peran('pemilik') THEN
        RAISE EXCEPTION 'Hanya pemilik yang dapat mengatur peran pengguna.';
    END IF;

    IF p_peran NOT IN ('pemilik', 'admin', 'kurir', 'nonaktif') THEN
        RAISE EXCEPTION 'Peran tidak dikenal: %', p_peran;
    END IF;

    IF p_user_id = auth.uid() THEN
        RAISE EXCEPTION 'Anda tidak dapat mengubah peran akun Anda sendiri.';
    END IF;

    UPDATE auth.users
    SET raw_app_meta_data  = COALESCE(raw_app_meta_data, '{}'::JSONB)
                             || jsonb_build_object('peran', p_peran),
        email_confirmed_at = CASE WHEN p_peran = 'nonaktif' THEN email_confirmed_at
                                  ELSE COALESCE(email_confirmed_at, NOW()) END
    WHERE id = p_user_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pengguna tidak ditemukan.';
    END IF;
END;
$$;


